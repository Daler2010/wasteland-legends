// Зомби-великан и Матка слизней: тот же рисунок вдвое крупнее, со своей палитрой и добавками
function paintGiant(pose) {
  return paintSprite(48, 54, (R) => ENEMY_PAINT.zombie(R, pose, ENEMY_PAL.giant), x => x.scale(2, 2));
}
function paintQueen(pose) {
  return paintSprite(48, 50, (R, x) => {
    ENEMY_PAINT.slime(R, pose, ENEMY_PAL.queen);
    // корона и зубы рисуем уже в мелком масштабе
    x.setTransform(1, 0, 0, 1, 0, 0);
    R(14, 12, 20, 7, '#ffcd75'); R(14, 17, 20, 2, '#d59a3b');
    R(14, 6, 4, 6, '#ffcd75'); R(22, 3, 4, 9, '#ffcd75'); R(30, 6, 4, 6, '#ffcd75');
    R(23, 13, 2, 3, '#ef3b5b'); R(16, 14, 2, 2, '#73eff7'); R(30, 14, 2, 2, '#73eff7');
    R(22, 3, 1, 3, EW);
  }, x => { x.translate(0, 12); x.scale(2, 2); });
}

const ENEMY_SIZE = {
  zombie: [24, 27], rat: [27, 16], slime: [24, 18], marauder: [26, 28], bomber: [24, 26],
  drone: [26, 18], brute: [29, 30], necro: [25, 28], scorpion: [52, 48], robot: [48, 53], alan: [52, 58],
};
const ENEMY_POSES = { '': { f: 0 }, _a: { f: 0 }, _b: { f: 1 }, _atk: { f: 0, atk: true } };

function buildEnemySprites() {
  for (const id in ENEMY_SIZE) {
    const [w, h] = ENEMY_SIZE[id];
    for (const suffix in ENEMY_POSES) {
      registerSprite(id + suffix, paintSprite(w, h, R => ENEMY_PAINT[id](R, ENEMY_POSES[suffix], ENEMY_PAL[id])));
    }
  }
  for (const suffix in ENEMY_POSES) {
    registerSprite('giant' + suffix, paintGiant(ENEMY_POSES[suffix]));
    registerSprite('queen' + suffix, paintQueen(ENEMY_POSES[suffix]));
  }
}
