function paintSprite(w, h, fn, setup) {
  const c = makeCanvas(w, h), x = c.getContext('2d');
  if (setup) setup(x);
  const R = (X, Y, W, H, col) => { x.fillStyle = col; x.fillRect(X, Y, W, H); };
  fn(R, x);
  outlineSprite(c);
  shadeSprite(c);
  return c;
}

